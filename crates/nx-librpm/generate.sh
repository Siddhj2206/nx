#!/usr/bin/env bash
# Regenerates src/sys.rs from the installed librpm headers (ADR-0008).
# Run inside the dev container: dev/run crates/nx-librpm/generate.sh
set -euo pipefail
cd "$(dirname "$0")"

cat > /tmp/nx-librpm.h <<'H'
#include <rpm/rpmlib.h>
#include <rpm/rpmts.h>
#include <rpm/rpmio.h>
#include <rpm/rpmlog.h>
#include <rpm/rpmkeyring.h>
#include <rpm/rpmpgp.h>
#include <rpm/rpmfiles.h>
#include <rpm/rpmfi.h>
#include <rpm/rpmarchive.h>
#include <rpm/header.h>
#include <rpm/rpmtag.h>
H

{
	echo "// Generated by generate.sh from rpm $(rpm -q --qf '%{VERSION}' rpm-devel); do not edit."
	bindgen /tmp/nx-librpm.h \
		--allowlist-function 'rpmReadConfigFiles|rpmReadPackageFile|rpmts(Create|Free|SetKeyring|SetVSFlags)|rpmKeyring(New|Free|AddKey)|rpmPubkey(New|Free|FingerprintAsHex)|rpmGetSubkeys|pgpParsePkts|rpmfiles(New|Free)|rpmfi(NewArchiveReader|Free|Next|FN|FMode|FLink|FMtime|FDigestHex|FCaps|FX|FLinks|ArchiveRead|ArchiveHasContent|ArchiveClose)|header(Free|GetString|IsEntry)|Fopen|Fdopen|Fclose|Ferror|Fstrerror|rpmlog(SetCallback|Message)|rfree' \
		--allowlist-type 'rpmRC_e|rpmTag_e|rpmVSFlags_e|rpmfiFlags_e|rpmFileIter_e|pgpArmor_e' \
		--default-enum-style consts --no-prepend-enum-name \
		--no-layout-tests --no-doc-comments \
		-- -I/usr/include
} > src/sys.rs
echo "wrote src/sys.rs ($(wc -l < src/sys.rs) lines)"
