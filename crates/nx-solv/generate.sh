#!/usr/bin/env bash
# Regenerates src/sys.rs from the installed libsolv headers (ADR-0007).
# Run inside the dev container: dev/run crates/nx-solv/generate.sh
set -euo pipefail
cd "$(dirname "$0")"

cat > /tmp/nx-solv.h <<'H'
#include <solv/pool.h>
#include <solv/poolarch.h>
#include <solv/repo.h>
#include <solv/repo_solv.h>
#include <solv/repo_write.h>
#include <solv/repo_rpmdb.h>
#include <solv/repo_rpmmd.h>
#include <solv/repo_repomdxml.h>
#include <solv/solver.h>
#include <solv/solverdebug.h>
#include <solv/transaction.h>
#include <solv/selection.h>
#include <solv/evr.h>
#include <solv/knownid.h>
#include <solv/solv_xfopen.h>
#include <solv/queue.h>
#include <solv/bitmap.h>
H

{
	echo "// Generated by generate.sh from libsolv $(rpm -q --qf '%{VERSION}' libsolv-devel); do not edit."
	bindgen /tmp/nx-solv.h \
		--allowlist-function 'pool_.*|repo_.*|solver_.*|solvable_.*|transaction_.*|selection_.*|queue_.*|map_.*|solv_xfopen.*|solv_free|solv_calloc|pool_evrcmp_str|testcase_.*|dataiterator_.*|repodata_dir2str' \
		--allowlist-type 'Pool|Repo|Solvable|Solver|Transaction|Queue|Map|Id|Offset|solv_knownid|Dataiterator' --default-enum-style consts --no-prepend-enum-name \
		--allowlist-var 'SOLVER_.*|SOLVABLE_.*|REPO_.*|SELECTION_.*|SEARCH_.*|EVRCMP_.*|RPM_ADD_.*|ID_.*|SOLVID_META|REL_.*|DISTTYPE_.*|POOL_FLAG_.*|ARCH_.*|NUMTYPE_.*|TRANSACTION_.*' \
		--no-layout-tests --no-doc-comments \
		--blocklist-type '_IO_FILE|FILE' --raw-line 'pub type FILE = libc::FILE;' \
		-- -I/usr/include
} > src/sys.rs
echo "wrote src/sys.rs ($(wc -l < src/sys.rs) lines)"
